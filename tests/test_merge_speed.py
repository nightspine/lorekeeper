def tricky() -> dict:
    # one anchor per entity, so "who came first" never ties (a tie would follow set order, hash-seeded)
    return {"anchors": [{"id": f"a{n}", "seq": n} for n in range(len(NAMES))], "entities": [
        {"id": i, "type": t, "from": f"a{n}", "names": [{"value": v, "from": f"a{n}"} for v in ns],
         "facets": [{"id": f"{i}.f", "text": f"{ns[0]} is in the story.", "from": f"a{n}"}]}
        for n, (i, t, ns) in enumerate(NAMES)]}


def same(a: list[dict], b: list[dict]) -> bool:
    key = lambda l: sorted(json.dumps(x, sort_keys=True, ensure_ascii=False) for x in l)  # noqa: E731
    return key(a) == key(b)


FIX = json.loads((Path(__file__).parent / "fixtures" / "merge_candidates.json").read_text("utf-8"))


def test_tricky_index_unchanged():
    got = merge.candidates([tricky()], {frozenset(("p-dora", "p-dora2"))})
    assert FIX["tricky"] and same(got, FIX["tricky"])


@pytest.mark.parametrize("name", sorted(EXAMPLES))
def test_examples_unchanged(name):
    docs = [json.loads((ROOT / f).read_text("utf-8")) for f in EXAMPLES[name]]
    assert same(merge.candidates(docs), FIX[name])


def test_helpers_do_not_share_mutable_results():
    t = merge._titles("Mrs. Dursley")
    t.append("x")
    assert merge._titles("Mrs. Dursley") == ["mrs"]


def test_names_are_parsed_once_not_once_per_pair(monkeypatch):
    # 600 entities make 180k pairs; the uncached loop split every name again for every pair (millions of
    # calls). Counting calls instead of seconds keeps this independent of the machine.
    ents = [{"id": f"p{i}", "type": "person", "from": "a1", "names": [{"value": f"Name{i} Surname{i % 40}", "from": "a1"}]}
            for i in range(600)]
    doc = {"anchors": [{"id": "a1", "seq": 1}], "entities": ents}
    for f in vars(merge).values():
        if hasattr(f, "cache_clear"):
            f.cache_clear()
    calls = []
    real = merge.text.words
    monkeypatch.setattr(merge.text, "words", lambda t: calls.append(t) or real(t))
    merge.candidates([doc])
    assert len(calls) <= 3 * len(ents)


def test_caches_are_bounded():
    cached = [f for f in vars(merge).values() if hasattr(f, "cache_info")]
    assert len(cached) >= 7
    assert all(f.cache_info().maxsize is not None for f in cached)
