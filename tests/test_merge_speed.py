    ("p-voss1", "person", ["Fabién Voss"]), ("p-voss2", "person", ["Danton Voss"]), ("p-voss3", "person", ["Laure Voss"]),
    ("p-voss", "person", ["Voss"]), ("p-capt", "person", ["Capitaine"]), ("p-frere", "person", ["Frère Greyhand"]),
