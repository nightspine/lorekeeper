"""`merge.candidates` is cached per name and must give exactly what the plain pair loop gave.

`fixtures/merge_candidates.json` was generated by the implementation before the caching was added
(uncached helpers, every pair compared), on the examples and on `tricky()`, an index built to hit every
rule in `extends`. The order of pairs inside one group follows set iteration, so compare as sets.
"""

