"""`merge.candidates` is cached per name and must give exactly what the plain pair loop gave.

`fixtures/merge_candidates.json` was generated by the implementation before the caching was added
(uncached helpers, every pair compared), on the examples and on `tricky()`, an index built to hit every
rule in `extends`. The order of pairs inside one group follows set iteration, so compare as sets.
"""

import json
import time
from pathlib import Path

import pytest

from lorekeeper import merge

ROOT = Path(__file__).parent.parent
EXAMPLES = {
    "sherlock": ["examples/sherlock-holmes/study-in-scarlet.json", "examples/sherlock-holmes/sign-of-four.json"],
    "dracula": ["examples/dracula/dracula.json"],
}
NAMES = [
    ("p-dior", "person", ["Dior"]), ("p-dior2", "person", ["Dior LaChance"]),
    ("p-snape", "person", ["Professor Snape"]), ("p-severus", "person", ["Severus Snape"]),
    ("p-mr", "person", ["Mr. Dursley"]), ("p-mrs", "person", ["Mrs. Dursley"]), ("p-vernon", "person", ["Vernon Dursley"]),
    ("p-vh", "person", ["Van Helsing"]), ("p-avh", "person", ["Abraham Van Helsing"]),
    ("p-q", "person", ["Quincey Morris"]), ("p-qp", "person", ["Quincey P. Morris"]), ("p-qpeter", "person", ["Quincey Peter Morris"]),
    ("p-kiara", "person", ["Kiara"]), ("p-wolf", "person", ["Wolfmother Kiara"]),
    ("p-voss1", "person", ["Fabién Voss"]), ("p-voss2", "person", ["Danton Voss"]), ("p-voss3", "person", ["Laure Voss"]),
    ("p-voss", "person", ["Voss"]), ("p-capt", "person", ["Capitaine"]), ("p-frere", "person", ["Frère Greyhand"]),
    ("p-grey", "person", ["Greyhand"]), ("p-dora", "person", ["Dora"]), ("p-dora2", "person", ["Dora Clay"]),
    ("p-poss", "person", ["Gabriel's daughter"]), ("p-gab", "person", ["Gabriel", "Gabe (the narrator)"]),
    ("p-gab2", "person", ["Gabriel de León"]),
    ("t-mug", "creature", ["Muggles"]), ("t-mug2", "creature", ["Muggle"]),
    ("o-mirror", "object", ["Mirror of Erised"]), ("o-mirror2", "object", ["Erised mirror"]),
    ("l-coste", "place", ["Coste"]), ("l-cath", "place", ["Coste Cathedral"]),
]


def tricky() -> dict:
    # one anchor per entity, so "who came first" never ties (a tie would follow set order, hash-seeded)
    return {"anchors": [{"id": f"a{n}", "seq": n} for n in range(len(NAMES))], "entities": [
        {"id": i, "type": t, "from": f"a{n}", "names": [{"value": v, "from": f"a{n}"} for v in ns],
         "facets": [{"id": f"{i}.f", "text": f"{ns[0]} is in the story.", "from": f"a{n}"}]}
        for n, (i, t, ns) in enumerate(NAMES)]}


def same(a: list[dict], b: list[dict]) -> bool:
    key = lambda l: sorted(json.dumps(x, sort_keys=True, ensure_ascii=False) for x in l)  # noqa: E731
    return key(a) == key(b)


FIX = json.loads((Path(__file__).parent / "fixtures" / "merge_candidates.json").read_text("utf-8"))


def test_tricky_index_unchanged():
    got = merge.candidates([tricky()], {frozenset(("p-dora", "p-dora2"))})
    assert FIX["tricky"] and same(got, FIX["tricky"])


@pytest.mark.parametrize("name", sorted(EXAMPLES))
def test_examples_unchanged(name):
    docs = [json.loads((ROOT / f).read_text("utf-8")) for f in EXAMPLES[name]]
    assert same(merge.candidates(docs), FIX[name])


def test_helpers_do_not_share_mutable_results():
    t = merge._titles("Mrs. Dursley")
    t.append("x")
    assert merge._titles("Mrs. Dursley") == ["mrs"]


def test_many_entities_are_fast():
    # 600 entities, 180k pairs: the uncached loop needed seconds
    ents = [{"id": f"p{i}", "type": "person", "from": "a1", "names": [{"value": f"Name{i} Surname{i % 40}", "from": "a1"}]}
            for i in range(600)]
    doc = {"anchors": [{"id": "a1", "seq": 1}], "entities": ents}
    t = time.perf_counter()
    merge.candidates([doc])
    assert time.perf_counter() - t < 3
